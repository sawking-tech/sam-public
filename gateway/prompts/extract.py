"""Промпт извлечения фактов перед сжатием истории (SAM-63, ADR-015).

Модель получает кусок разговора, который сжатие сейчас уберёт из истории, и возвращает устойчивые факты
о людях дома и их жизни - одним JSON-объектом. Только сказанное людьми или подтверждённое ими; догадки и
болтовня SAM фактами не становятся (то же правило веса источника, что в SUMMARIZE_BASE_PROMPT).
"""

EXTRACT_FACTS_PROMPT = """Ниже кусок моего разговора с домашними, он уходит из активной истории.
Выпиши из него устойчивые факты, которые стоит помнить дольше этого разговора: о домашних и близких,
их планах, предпочтениях, договорённостях, людях и животных вокруг них.

Правила:
- Только то, что сказали люди (user) или подтвердили. Мои (assistant) предложения, догадки и шутки - не факты.
- Каждый факт - одно законченное предложение от третьего лица, понятное без этого разговора
  («<кличка> - кошка <имя хозяйки, как в разговоре>», а не «она кошка»).
- Не выдумывай и не обобщай. Разовые просьбы («открой музыку»), приветствия и команды - не факты.
- Личные данные гостей не записывай.
- Нет фактов - верни пустой список.

Ответь ровно одним JSON-объектом, без пояснений:
{{"facts": [{{"text": "...", "summary": "до 80 знаков", "questions": ["вопрос, на который факт отвечает"]}}]}}

Разговор:
{text}
"""
