"""Граница компетенции быстрой модели (SAM-169): кто отвечает на фразу человека - быстрая или основная.

Быстрая отвечает за доли секунды, но знает только контекст хода и выдумывает факт, которого в нём нет («какая погода
дома» - «тихо, вечерний свет», 12 окт). Поэтому код по фразе до ответа, как reply_class по ответу: вопрос о факте вне
разговора и просьба о действии - по существу отвечает и делает основная отложенным вызовом, быстрая коротко берёт паузу
(«посмотрю», «сделаю»): своих вызовов у быстрой нет, она знает только список возможностей SAM. Остальное (болтовня,
подтверждение, переспрос, вопрос о самой SAM, время и дата - они в контексте хода) - быстрой. Слова - формы целиком,
без «любое слово с основы».
"""
from __future__ import annotations

import os
import re

FAST, MAIN = "fast", "main"

# Повелительное наклонение действий на устройствах и в мире (ед. и мн. число)
ACTION_VERBS = (
    "включи|включите|выключи|выключите|поставь|поставьте|открой|откройте|закрой|закройте|запусти|запустите|"
    "перезапусти|перезапустите|найди|найдите|поищи|поищите|напомни|напомните|запиши|запишите|запомни|запомните|"
    "удали|удалите|отправь|отправьте|проверь|проверьте|посмотри|посмотрите|узнай|узнайте|скачай|скачайте|"
    "сделай|сделайте|создай|создайте|добавь|добавьте|убавь|прибавь|отмени|отмените|заведи|разбуди|"
    "покажи|покажите|позвони|напиши|закажи|сохрани|почини|обнови|установи|"
    # быт: SAM этого может не уметь - тогда пауза и честный ответ основной, а не «сейчас сделаю»
    "вымой|помой|убери|уберите|приготовь|свари|разогрей|принеси|купи|полей|покорми|выгуляй|погладь|постирай|"
    "вынеси|подогрей|сходи|съезди|забери|переведи|оплати|вызови"
)
# Дополнительные формы без правки кода: SAM_ACTION_VERBS_EXTRA=«форма|форма»
ACTION_VERBS_EXTRA = os.getenv("SAM_ACTION_VERBS_EXTRA", "").strip(" |")
# Вопрос о мире и предметы мира (погода, курс, новости): чего нет в контексте хода
FACT_QUESTIONS = (
    r"сколько|когда|где|откуда|почему|зачем|что такое|кто такой|кто такая|что значит|что нового|"
    r"погода|погоду|погоде|погодой|температура|температуру|курс|курса|новости|новостей"
)
# В контексте хода есть сами: время и дата идут строкой системного сообщения (runner.build_messages)
IN_CONTEXT = r"который час|сколько времени|какое сегодня число|какой сегодня день|какое число|какой день"
# Вопрос к самой SAM («почему ты молчишь», «где ты была») - болтовня, а не факт о мире: отвечает быстрая (ревью 12 окт)
ABOUT_SAM = r"ты|тебя|тебе|тобой|твой|твоя|твоё|твое|твои"

_ACTION = re.compile(rf"(?<![\w-])(?:{ACTION_VERBS}{'|' + ACTION_VERBS_EXTRA if ACTION_VERBS_EXTRA else ''})(?![\w-])", re.I)
_FACT = re.compile(rf"(?<![\w-])(?:{FACT_QUESTIONS})(?![\w-])", re.I)
_ABOUT_SAM = re.compile(rf"(?<![\w-])(?:{ABOUT_SAM})(?![\w-])", re.I)
_IN_CONTEXT = re.compile(rf"(?<![\w-])(?:{IN_CONTEXT})(?![\w-])", re.I)


def responder_for(phrase: str) -> str:
    """MAIN - просьба о действии или вопрос о факте вне контекста хода: по существу - основная; иначе FAST."""
    text = phrase or ""
    if _ACTION.search(text):
        return MAIN
    if _FACT.search(text) and not _IN_CONTEXT.search(text) and not _ABOUT_SAM.search(text):
        return MAIN
    return FAST
