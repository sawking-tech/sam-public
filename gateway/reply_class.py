"""Класс реплики быстрой модели для проверки пачками (SAM-56, ADR-014).

Основная модель медленная, поэтому ответы быстрой проверяются не каждый, а пачками по времени
. Ошибка в действии и в факте
стоит дороже всего - человек поверит, что будильник поставлен, - поэтому такие реплики проверяются сразу,
остальные ждут пачки. Правила по порядку, первое сработавшее решает:

1. глагол действия первого лица («открыла», «поставлю», «записал», «проверим»), а spawn_agent в ходе не
   вызван - ACTION_UNBACKED: быстрая говорит о действии, которого никто не запускал;
2. тот же глагол при вызванном spawn_agent - ACTION: действие запущено, проверить, то ли;
3. цифра, числительное, единица времени или имя файла - FACT;
4. остальное - CHATTER: поддакивание, вопрос, шутка, пересказ сказанного.

Ошибается в сторону срочного: «ты сделал» и «что делаю» тоже глагол действия, лишняя проверка дешевле
непойманного «поставила». Список глаголов - бытовые действия SAM и действия над файлами; новый глагол -
строка в ACTION_STEMS. Логика без модели и сети: на вход текст и имена вызванных tools, на выход класс.
"""
from __future__ import annotations

import re
from typing import Iterable

ACTION_UNBACKED, ACTION, FACT, CHATTER = "action_unbacked", "action", "fact", "chatter"
URGENT = frozenset({ACTION_UNBACKED, ACTION, FACT})
SPAWN_TOOL = "spawn_agent"   # единственный tool голосового пути: им запускается действие

# Глаголы действия: прошедшее первого лица (оба рода), будущее и настоящее первого лица, «мы» будущее.
# Формы перечислены целиком, без «любое слово с основы»: иначе «поставщик» и «записи» - действие
ACTION_STEMS = (
    "открыл|открыла|открою|открываю|откроем",
    "закрыл|закрыла|закрою|закрываю|закроем",
    "поставил|поставила|поставлю|ставлю|поставим",
    "записал|записала|запишу|записываю|запишем",
    "запустил|запустила|запущу|запускаю|запустим",
    "перезапустил|перезапустила|перезапущу|перезапускаю|перезапустим",
    "включил|включила|включу|включаю|включим|выключил|выключила|выключу|выключаю|выключим",
    "сохранил|сохранила|сохраню|сохраняю|сохраним",
    "удалил|удалила|удалю|удаляю|удалим",
    "добавил|добавила|добавлю|добавляю|добавим",
    "создал|создала|создам|создаю|создадим|завёл|завел|завела|заведу|заведём|заведем",
    "отправил|отправила|отправлю|отправляю|отправим",
    "нашёл|нашел|нашла|найду|ищу|найдём|найдем|поищу",
    "проверил|проверила|проверю|проверяю|проверим|сверил|сверила|сверю|сверяю|сверим",
    "исправил|исправила|исправлю|исправляю|исправим|починил|починила|починю|чиню|починим",
    "перенёс|перенес|перенесла|перенесу|переношу|перенесём|перенесем",
    "напомнил|напомнила|напомню|напомним",
    "запомнил|запомнила|запомню|запоминаю",
    "подключил|подключила|подключу|подключаю|подключим",
    "установил|установила|установлю|устанавливаю|установим",
    "обновил|обновила|обновлю|обновляю|обновим",
    "сделал|сделала|сделаю|делаю|сделаем",
    "загрузил|загрузила|загружу|загружаю|загрузим",
    "посмотрел|посмотрела|посмотрю|посмотрим|гляну|глянула|глянул",
    "отменил|отменила|отменю|отменяю|отменим",
    "скачал|скачала|скачаю|скачиваю|скачаем",
)
# Числительные и единицы: «в семь», «полчаса», «через две минуты». Порядковые не входят: «во-первых»
NUMBER_WORDS = (
    "ноль|один|одна|одно|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|одиннадцать|"
    "двенадцать|пятнадцать|двадцать|тридцать|сорок|пятьдесят|сто|двести|тысяч[аиу]?|миллион\\w*|"
    "полтора|полторы|половин[ауы]|четверть|пол[её]?часа|"
    "секунд[аыу]?|минут[аыу]?|час|часа|часов|сутки|суток|процент\\w*"
)
_ACTION = re.compile(rf"(?<![\w-])(?:{'|'.join(ACTION_STEMS)})(?![\w-])", re.I)
_NUMBER = re.compile(rf"\d|(?<![\w-])(?:{NUMBER_WORDS})(?![\w-])", re.I)
# Имя файла: слово с расширением в 1-5 букв («task.cs», «CLAUDE.md»), не конец предложения «дальше.Да»
_FILE = re.compile(r"(?<![\w.])[\w-]+\.[a-z][a-z0-9]{0,4}(?![\w])")


def classify(voice: str, tools: Iterable[str] = ()) -> str:
    """Класс реплики быстрой: ACTION_UNBACKED, ACTION, FACT или CHATTER."""
    text = voice or ""
    if _ACTION.search(text):
        return ACTION if SPAWN_TOOL in set(tools) else ACTION_UNBACKED
    if _NUMBER.search(text) or _FILE.search(text):
        return FACT
    return CHATTER


def is_urgent(kind: str) -> bool:
    """Срочное проверяется сразу, разговорное ждёт пачки."""
    return kind in URGENT
